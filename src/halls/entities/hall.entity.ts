import { ApiProperty } from '@nestjs/swagger';
import { Column, Entity, OneToMany, PrimaryGeneratedColumn } from 'typeorm';
import { MAX_NAME_LENGTH } from '../../common/column-limits';
import { Showing } from '../../showings/entities/showing.entity';

/**
 * The seats of a hall are not stored: the service computes them from `rows`
 * and `seatsPerRow`.
 */
@Entity('halls')
export class Hall {
  @ApiProperty({ format: 'uuid', description: 'Generated by the database' })
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @ApiProperty({ example: 'Red hall', description: 'Unique among all halls' })
  @Column({ type: 'varchar', length: MAX_NAME_LENGTH, unique: true })
  name: string;

  @ApiProperty({ example: 3, minimum: 1 })
  @Column({ type: 'integer' })
  rows: number;

  @ApiProperty({ example: 5, minimum: 1 })
  @Column({ name: 'seats_per_row', type: 'integer' })
  seatsPerRow: number;

  /** A hall has many showings; the foreign key is `showings.hall_id`. */
  @OneToMany(() => Showing, (showing) => showing.hall)
  showings?: Showing[];
}
