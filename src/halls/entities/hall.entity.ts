import { ApiProperty } from '@nestjs/swagger';
import { Seat } from './seat.entity';

export class Hall {
  @ApiProperty({ format: 'uuid', description: 'Generated by the server' })
  id: string;

  @ApiProperty({ example: 'Red hall', description: 'Unique among all halls' })
  name: string;

  @ApiProperty({ example: 3, minimum: 1 })
  rows: number;

  @ApiProperty({ example: 5, minimum: 1 })
  seatsPerRow: number;
}

export class HallWithSeats extends Hall {
  @ApiProperty({
    type: [Seat],
    description: 'Every seat of the hall, computed from rows and seatsPerRow',
  })
  seats: Seat[];
}
