import {
  BadRequestException,
  ConflictException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { InjectDataSource, InjectRepository } from '@nestjs/typeorm';
import { DataSource, FindOptionsOrder, Repository } from 'typeorm';
import { MAX_INTEGER } from '../common/column-limits';
import { isPostgresError, PostgresErrorCode } from '../common/postgres-error';
import { Seat } from '../halls/dto/seat.dto';
import { HallsService } from '../halls/halls.service';
import { ShowingsService } from '../showings/showings.service';
import { BookingView } from './dto/booking-view.dto';
import { CreateBookingDto } from './dto/create-booking.dto';
import { SeatStatus } from './dto/seat-status.dto';
import { BookingSeat } from './entities/booking-seat.entity';
import { Booking } from './entities/booking.entity';

const seatKey = ({ row, seat }: Seat): string => `${row}:${seat}`;
const describeSeat = ({ row, seat }: Seat): string => `row ${row} seat ${seat}`;
const bySeat = (a: Seat, b: Seat): number => a.row - b.row || a.seat - b.seat;

/** Oldest booking first; the seats of a booking by row and seat. */
const BOOKINGS_ORDER: FindOptionsOrder<Booking> = {
  createdAt: 'ASC',
  id: 'ASC',
  seats: { row: 'ASC', seat: 'ASC' },
};

@Injectable()
export class BookingsService {
  constructor(
    @InjectRepository(Booking)
    private readonly bookingsRepository: Repository<Booking>,
    @InjectRepository(BookingSeat)
    private readonly bookingSeatsRepository: Repository<BookingSeat>,
    @InjectDataSource()
    private readonly dataSource: DataSource,
    private readonly showingsService: ShowingsService,
    private readonly hallsService: HallsService,
  ) {}

  async findAll(): Promise<BookingView[]> {
    const bookings = await this.bookingsRepository.find({
      relations: { seats: true },
      order: BOOKINGS_ORDER,
    });
    return bookings.map((booking) => this.toView(booking));
  }

  async findByShowing(showingId: string): Promise<BookingView[]> {
    await this.showingsService.findOne(showingId);
    const bookings = await this.bookingsRepository.find({
      where: { showingId },
      relations: { seats: true },
      order: BOOKINGS_ORDER,
    });
    return bookings.map((booking) => this.toView(booking));
  }

  /**
   * Writes the booking and all of its seats in one transaction.
   *
   * Whether a seat is free is decided by the unique index on
   * (showing_id, row, seat), not by a query made here, so two simultaneous
   * requests cannot both get the same seat. If the index rejects a seat, the
   * transaction is rolled back and neither the booking nor any seat remains.
   */
  async create(showingId: string, dto: CreateBookingDto): Promise<BookingView> {
    const showing = await this.showingsService.findOne(showingId);
    const hall = await this.hallsService.findOne(showing.hallId);

    const missing = dto.seats.filter(
      (seat) => seat.row > hall.rows || seat.seat > hall.seatsPerRow,
    );
    if (missing.length > 0) {
      throw new BadRequestException(
        `Hall "${hall.name}" has ${hall.rows} rows of ${hall.seatsPerRow} seats, so these seats do not exist: ${missing.map(describeSeat).join(', ')}`,
      );
    }

    const totalPrice = showing.price * dto.seats.length;
    if (totalPrice > MAX_INTEGER) {
      throw new BadRequestException(
        `The total price ${totalPrice} is larger than the maximum of ${MAX_INTEGER}`,
      );
    }

    // Always the same order, so that simultaneous bookings of overlapping
    // seats wait for each other instead of deadlocking.
    const requested = dto.seats
      .map(({ row, seat }) => ({ row, seat }))
      .sort(bySeat);

    try {
      const booking = await this.dataSource.transaction(async (manager) => {
        // Inside the callback only `manager` may be used: the injected
        // repositories work on other connections, outside the transaction.
        const created = manager.create(Booking, { showingId, totalPrice });
        await manager.save(created);

        // The booking id is generated by the insert above.
        const seats = requested.map(({ row, seat }) =>
          manager.create(BookingSeat, {
            bookingId: created.id,
            showingId,
            row,
            seat,
          }),
        );
        created.seats = await manager.save(seats);

        return created;
      });
      return this.toView(booking);
    } catch (error) {
      // The catch is around `transaction()`, so the rollback has already
      // happened. Every other database failure stays a server error.
      if (isPostgresError(error, PostgresErrorCode.UniqueViolation)) {
        throw new ConflictException(
          await this.describeConflict(showingId, requested),
        );
      }
      throw error;
    }
  }

  async seatMap(showingId: string): Promise<SeatStatus[]> {
    const showing = await this.showingsService.findOne(showingId);
    const hall = await this.hallsService.findOne(showing.hallId);
    const taken = await this.bookedSeatKeys(showingId);

    return this.hallsService
      .listSeats(hall)
      .map((seat) => ({ ...seat, isBooked: taken.has(seatKey(seat)) }));
  }

  /**
   * Deletes only the booking row. Its seats are deleted by the database
   * through ON DELETE CASCADE on `booking_seats.booking_id`.
   */
  async remove(id: string): Promise<void> {
    const { affected } = await this.bookingsRepository.delete({ id });
    if (!affected) {
      throw new NotFoundException(`Booking with id ${id} not found`);
    }
  }

  /**
   * The 409 message is written here and names the taken seats.
   * The text of the database error never reaches the client.
   */
  private async describeConflict(
    showingId: string,
    requested: Seat[],
  ): Promise<string> {
    const taken = await this.bookedSeatKeys(showingId);
    const conflicts = requested.filter((seat) => taken.has(seatKey(seat)));

    return conflicts.length > 0
      ? `Already booked on this showing: ${conflicts.map(describeSeat).join(', ')}`
      : 'One or more of the requested seats are already booked on this showing';
  }

  private async bookedSeatKeys(showingId: string): Promise<Set<string>> {
    const seats = await this.bookingSeatsRepository.find({
      select: { row: true, seat: true },
      where: { showingId },
    });
    return new Set(seats.map(seatKey));
  }

  private toView(booking: Booking): BookingView {
    return {
      id: booking.id,
      showingId: booking.showingId,
      seats: (booking.seats ?? []).map(({ row, seat }) => ({ row, seat })),
      totalPrice: booking.totalPrice,
    };
  }
}
