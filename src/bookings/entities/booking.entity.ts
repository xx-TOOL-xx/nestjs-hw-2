import { ApiProperty } from '@nestjs/swagger';
import { Seat } from '../../halls/entities/seat.entity';

export class Booking {
  @ApiProperty({ format: 'uuid', description: 'Generated by the server' })
  id: string;

  @ApiProperty({ format: 'uuid' })
  showingId: string;

  @ApiProperty({ type: [Seat] })
  seats: Seat[];

  @ApiProperty({
    example: 25000,
    description:
      'Showing price multiplied by the number of seats, in the smallest currency unit',
  })
  totalPrice: number;
}
