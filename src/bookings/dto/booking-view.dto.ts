import { ApiProperty } from '@nestjs/swagger';
import { Seat } from '../../halls/dto/seat.dto';

/** A booking as clients read it: its seats are a plain list of positions. */
export class BookingView {
  @ApiProperty({ format: 'uuid', description: 'Generated by the database' })
  id: string;

  @ApiProperty({ format: 'uuid' })
  showingId: string;

  @ApiProperty({
    type: [Seat],
    description: 'Booked seats, ordered by row and seat',
  })
  seats: Seat[];

  @ApiProperty({
    example: 25000,
    description:
      'Showing price multiplied by the number of seats, in the smallest currency unit',
  })
  totalPrice: number;
}
