import { ApiProperty } from '@nestjs/swagger';
import { Column, Entity, OneToMany, PrimaryGeneratedColumn } from 'typeorm';
import { MAX_NAME_LENGTH } from '../../common/column-limits';
import { Showing } from '../../showings/entities/showing.entity';

@Entity('films')
export class Film {
  @ApiProperty({ format: 'uuid', description: 'Generated by the database' })
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @ApiProperty({ example: 'Dune: Part Two' })
  @Column({ type: 'varchar', length: MAX_NAME_LENGTH })
  title: string;

  @ApiProperty({ example: 166, minimum: 1, description: 'Length in minutes' })
  @Column({ name: 'duration_minutes', type: 'integer' })
  durationMinutes: number;

  @ApiProperty({ example: 2024 })
  @Column({ name: 'release_year', type: 'integer' })
  releaseYear: number;

  /** A film has many showings; the foreign key is `showings.film_id`. */
  @OneToMany(() => Showing, (showing) => showing.film)
  showings?: Showing[];
}
