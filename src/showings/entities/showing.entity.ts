import { ApiProperty } from '@nestjs/swagger';
import {
  Column,
  Entity,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
} from 'typeorm';
import { Film } from '../../films/entities/film.entity';
import { Hall } from '../../halls/entities/hall.entity';

@Entity('showings')
export class Showing {
  @ApiProperty({ format: 'uuid', description: 'Generated by the database' })
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @ApiProperty({ format: 'uuid' })
  @Column({ name: 'film_id', type: 'uuid' })
  filmId: string;

  @ApiProperty({ format: 'uuid' })
  @Column({ name: 'hall_id', type: 'uuid' })
  hallId: string;

  @ApiProperty({
    type: String,
    format: 'date-time',
    example: '2030-05-01T18:30:00.000Z',
    description: 'Start time, ISO 8601, stored in UTC',
  })
  @Column({ name: 'starts_at', type: 'timestamptz' })
  startsAt: Date;

  @ApiProperty({
    example: 12500,
    minimum: 1,
    description: 'Price of one ticket in the smallest currency unit',
  })
  @Column({ type: 'integer' })
  price: number;

  /**
   * Required relation. Deleting a film never cascades to its showings:
   * the database rejects the delete while a showing refers to the film.
   */
  @ManyToOne(() => Film, (film) => film.showings, {
    nullable: false,
    onDelete: 'NO ACTION',
  })
  @JoinColumn({ name: 'film_id' })
  film?: Film;

  /** Required relation, protected from cascade deletes like `film`. */
  @ManyToOne(() => Hall, (hall) => hall.showings, {
    nullable: false,
    onDelete: 'NO ACTION',
  })
  @JoinColumn({ name: 'hall_id' })
  hall?: Hall;
}
