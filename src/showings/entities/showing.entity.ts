import { ApiProperty } from '@nestjs/swagger';

export class Showing {
  @ApiProperty({ format: 'uuid', description: 'Generated by the server' })
  id: string;

  @ApiProperty({ format: 'uuid' })
  filmId: string;

  @ApiProperty({ format: 'uuid' })
  hallId: string;

  @ApiProperty({
    example: '2030-05-01T18:30:00.000Z',
    description: 'Start time, ISO 8601, stored in UTC',
  })
  startsAt: string;

  @ApiProperty({
    example: 12500,
    minimum: 1,
    description: 'Price of one ticket in the smallest currency unit',
  })
  price: number;
}
